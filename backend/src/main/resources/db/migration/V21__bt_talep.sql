-- V21 — BT (Bilgi Teknolojileri) talep kayitlari.
--
-- Talep DEPARTMANA atanir, kisiye degil: o departmandaki tum sorumlular ayni
-- listeyi gorur (urun karari). Bu yuzden sorumlu_id kolonu YOK; sorumlunun
-- gorecegi kayitlar kendi departman_id'si uzerinden suzulur.
--
-- Ilk surumde bilerek EKSIK olanlar (istenirse ayri migration ile eklenir):
--   durum      — is akisi (acik/islemde/kapandi) henuz tanimlanmadi. Bos anlamli
--                bir kolon koymak "bu ne demek" sorusunu cevapsiz birakirdi.
--   notlar     — sorumlunun kayit uzerine yazmasi ikinci bir tablo gerektiriyor.
--   oncelik    — "acil" tanimi yapilmadan konursa herkes acil isaretler.
-- Bu surumde talep tek yonlu: admin olusturur, sorumlu okur.

CREATE TABLE public.talep (
    id bigint NOT NULL,
    create_date timestamp(6) without time zone,
    update_date timestamp(6) without time zone,
    status boolean,
    hash_id character varying(36),
    departman_id bigint NOT NULL,
    baslik character varying(200) NOT NULL,
    aciklama character varying(4000),
    CONSTRAINT talep_departman_fk
        FOREIGN KEY (departman_id) REFERENCES public.departman(id)
);

ALTER TABLE public.talep ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.talep_id_seq
    START WITH 1 INCREMENT BY 1 NO MINVALUE NO MAXVALUE CACHE 1
);

ALTER TABLE public.talep ADD CONSTRAINT talep_pkey PRIMARY KEY (id);

CREATE UNIQUE INDEX uq_talep_hash_id ON public.talep (hash_id);

-- Sorumlu ekraninin tek sorgusu "benim departmanimin silinmemis talepleri".
-- Kismi index: soft-delete edilmis kayitlar indexte yer kaplamaz.
CREATE INDEX idx_talep_departman_aktif
    ON public.talep (departman_id)
 WHERE status = true;
