-- V12 — ADIM 2: Sablon/Gorev sistemi (4 tablo).
--
-- Sistemin kalbi SNAPSHOT'tir: sablon atandiginda madde METINLERI kopyalanir.
-- Sablon sonradan degisirse atanmis gorevler DEGISMEZ (Gereksinim 3).
-- Bu yuzden staj_gorev_madde.madde_metni bir FK degil, bagimsiz bir metin kopyasidir.

-- ---- Sablon tarafi (degisebilir; "usta kopya") ----

CREATE TABLE public.gorev_sablonu (
    id bigint NOT NULL,
    create_date timestamp(6) without time zone,
    update_date timestamp(6) without time zone,
    status boolean,
    hash_id character varying(36),
    ad character varying(255) NOT NULL,
    aciklama character varying(2000),
    -- ER_DIAGRAM'da eksikti; ROADMAP:546 "her sablon departman + seviye ile etiketli"
    -- diyor ve sablonAta departman uyumunu kontrol ediyor. Bu yuzden zorunlu FK.
    departman_id bigint NOT NULL,
    seviye character varying(255) NOT NULL,
    aktif boolean DEFAULT true NOT NULL,
    CONSTRAINT gorev_sablonu_seviye_check
        CHECK (((seviye)::text = ANY ((ARRAY['LEVEL_1'::character varying, 'LEVEL_2'::character varying])::text[])))
);
ALTER TABLE public.gorev_sablonu ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.gorev_sablonu_id_seq
    START WITH 1 INCREMENT BY 1 NO MINVALUE NO MAXVALUE CACHE 1
);

CREATE TABLE public.sablon_maddesi (
    id bigint NOT NULL,
    create_date timestamp(6) without time zone,
    update_date timestamp(6) without time zone,
    status boolean,
    hash_id character varying(36),
    sablon_id bigint NOT NULL,
    madde_metni character varying(2000) NOT NULL,
    sira integer NOT NULL
);
ALTER TABLE public.sablon_maddesi ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.sablon_maddesi_id_seq
    START WITH 1 INCREMENT BY 1 NO MINVALUE NO MAXVALUE CACHE 1
);

-- ---- Staja atanmis taraf (dondurulmus kopya) ----

CREATE TABLE public.staj_gorev (
    id bigint NOT NULL,
    create_date timestamp(6) without time zone,
    update_date timestamp(6) without time zone,
    status boolean,
    hash_id character varying(36),
    staj_id bigint NOT NULL,
    -- Sadece IZ: hangi sablondan uretildi? Sablon silinirse kopya ayakta kalir.
    kaynak_sablon_id bigint,
    baslik character varying(255) NOT NULL,
    aciklama character varying(2000),
    seviye character varying(255) NOT NULL,
    durum character varying(255) NOT NULL,
    atanma_tarihi timestamp(6) without time zone NOT NULL,
    CONSTRAINT staj_gorev_seviye_check
        CHECK (((seviye)::text = ANY ((ARRAY['LEVEL_1'::character varying, 'LEVEL_2'::character varying])::text[]))),
    CONSTRAINT staj_gorev_durum_check
        CHECK (((durum)::text = ANY ((ARRAY['BEKLIYOR'::character varying, 'TAMAMLANDI'::character varying, 'ONAYLANDI'::character varying, 'REDDEDILDI'::character varying])::text[])))
);
ALTER TABLE public.staj_gorev ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.staj_gorev_id_seq
    START WITH 1 INCREMENT BY 1 NO MINVALUE NO MAXVALUE CACHE 1
);

CREATE TABLE public.staj_gorev_madde (
    id bigint NOT NULL,
    create_date timestamp(6) without time zone,
    update_date timestamp(6) without time zone,
    status boolean,
    hash_id character varying(36),
    staj_gorev_id bigint NOT NULL,
    -- KOPYA (snapshot). sablon_maddesi'na referans DEGIL.
    madde_metni character varying(2000) NOT NULL,
    sira integer NOT NULL,
    stajyer_notu character varying(4000),
    -- Sorumlunun sonradan ekledigi, sablonda olmayan madde.
    ozel_mi boolean DEFAULT false NOT NULL,
    durum character varying(255) NOT NULL,
    onaylayan_sorumlu_id bigint,
    onay_tarihi timestamp(6) without time zone,
    onay_notu character varying(2000),
    CONSTRAINT staj_gorev_madde_durum_check
        CHECK (((durum)::text = ANY ((ARRAY['BEKLIYOR'::character varying, 'TAMAMLANDI'::character varying, 'ONAYLANDI'::character varying, 'REDDEDILDI'::character varying])::text[])))
);
ALTER TABLE public.staj_gorev_madde ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.staj_gorev_madde_id_seq
    START WITH 1 INCREMENT BY 1 NO MINVALUE NO MAXVALUE CACHE 1
);

-- ---- Birincil anahtarlar ----
ALTER TABLE ONLY public.gorev_sablonu   ADD CONSTRAINT gorev_sablonu_pkey PRIMARY KEY (id);
ALTER TABLE ONLY public.sablon_maddesi   ADD CONSTRAINT sablon_maddesi_pkey PRIMARY KEY (id);
ALTER TABLE ONLY public.staj_gorev      ADD CONSTRAINT staj_gorev_pkey PRIMARY KEY (id);
ALTER TABLE ONLY public.staj_gorev_madde ADD CONSTRAINT staj_gorev_madde_pkey PRIMARY KEY (id);

-- ---- Tekillik ----
ALTER TABLE ONLY public.gorev_sablonu   ADD CONSTRAINT uq_gorev_sablonu_hash   UNIQUE (hash_id);
ALTER TABLE ONLY public.sablon_maddesi   ADD CONSTRAINT uq_sablon_maddesi_hash   UNIQUE (hash_id);
ALTER TABLE ONLY public.staj_gorev      ADD CONSTRAINT uq_staj_gorev_hash      UNIQUE (hash_id);
ALTER TABLE ONLY public.staj_gorev_madde ADD CONSTRAINT uq_staj_gorev_madde_hash UNIQUE (hash_id);

-- Ayni sablonda iki madde ayni sirada olamaz.
ALTER TABLE ONLY public.sablon_maddesi
    ADD CONSTRAINT uq_sablon_maddesi_sira UNIQUE (sablon_id, sira);

-- ---- Yabanci anahtarlar ----
ALTER TABLE ONLY public.gorev_sablonu
    ADD CONSTRAINT fk_gorev_sablonu_departman FOREIGN KEY (departman_id) REFERENCES public.departman(id);

-- Sablon silinirse maddeleri da gider (maddeler sablona aittir).
ALTER TABLE ONLY public.sablon_maddesi
    ADD CONSTRAINT fk_sablon_maddesi_sablon FOREIGN KEY (sablon_id) REFERENCES public.gorev_sablonu(id) ON DELETE CASCADE;

ALTER TABLE ONLY public.staj_gorev
    ADD CONSTRAINT fk_staj_gorev_staj FOREIGN KEY (staj_id) REFERENCES public.staj(id);

-- KRITIK: sablon silinse bile atanmis gorev ayakta kalir, sadece izi kopar.
ALTER TABLE ONLY public.staj_gorev
    ADD CONSTRAINT fk_staj_gorev_kaynak_sablon FOREIGN KEY (kaynak_sablon_id) REFERENCES public.gorev_sablonu(id) ON DELETE SET NULL;

-- Gorev silinirse maddeleri da gider (kopya, gorevin parcasi).
ALTER TABLE ONLY public.staj_gorev_madde
    ADD CONSTRAINT fk_staj_gorev_madde_gorev FOREIGN KEY (staj_gorev_id) REFERENCES public.staj_gorev(id) ON DELETE CASCADE;

ALTER TABLE ONLY public.staj_gorev_madde
    ADD CONSTRAINT fk_staj_gorev_madde_onaylayan FOREIGN KEY (onaylayan_sorumlu_id) REFERENCES public.sorumlu(id);

-- ---- Sorgu indeksleri ----
-- "Bu stajin gorevleri" ve "bu gorevin maddeleri" en sik calisan iki sorgu.
CREATE INDEX idx_staj_gorev_staj ON public.staj_gorev (staj_id);
CREATE INDEX idx_staj_gorev_madde_gorev ON public.staj_gorev_madde (staj_gorev_id);
-- Oneri sorgusu: departman + seviye + aktif.
CREATE INDEX idx_gorev_sablonu_oneri ON public.gorev_sablonu (departman_id, seviye, aktif);
